const std = @import("std");
const build_options = @import("build_options");
const compat = @import("../compat.zig");
const build_model = @import("model.zig");
const bundle = @import("cache_bundle.zig");

const magic = "cyna-build-artifact-v3\n";

pub fn restore(
    allocator: std.mem.Allocator,
    target: build_model.BuildTarget,
    output_path: []const u8,
    artifact_base_path: []const u8,
    emit: build_model.EmitOptions,
    graph_hash: []const u8,
) !bool {
    const paths = try cachePaths(allocator, target, output_path, artifact_base_path, emit, graph_hash);
    defer freePaths(allocator, paths);

    const entry = (try bundle.load(allocator, paths.metadata)) orelse return false;
    defer entry.deinit(allocator);
    const metadata = entry.metadata;
    var lines = std.mem.splitScalar(u8, metadata, '\n');
    if (!std.mem.eql(u8, lines.next() orelse return false, magic[0 .. magic.len - 1])) return false;
    if (!std.mem.eql(u8, lines.next() orelse return false, paths.key)) return false;

    var saw_input = false;
    while (lines.next()) |line| {
        if (line.len == 0) continue;
        if (!std.mem.startsWith(u8, line, "input ")) return false;
        const record = line[6..];
        const separator = std.mem.indexOfScalar(u8, record, ' ') orelse return false;
        const expected_hash = record[0..separator];
        const path = record[separator + 1 ..];
        var actual_hash: [64]u8 = undefined;
        hashFile(&actual_hash, allocator, path) catch return false;
        if (!std.mem.eql(u8, expected_hash, &actual_hash)) return false;
        saw_input = true;
    }
    if (!saw_input) return false;

    const primary = entry.artifact("primary") orelse return false;
    const sidecar = entry.artifact("link-metadata");
    const staticlib = target.output_kind == .staticlib;
    if (entry.artifacts.len != @as(usize, if (staticlib) 2 else 1) or (staticlib and sidecar == null)) return false;
    // Validate the full bundle before changing any requested output. Derived
    // ELF/bin/hex artifacts are regenerated by the command after restoration.
    try bundle.restoreArtifact(primary, output_path);
    if (staticlib) {
        const path = try std.fmt.allocPrint(allocator, "{s}.cyna-link.toml", .{output_path});
        defer allocator.free(path);
        try bundle.restoreArtifact(sidecar.?, path);
    }
    return true;
}

pub fn store(
    allocator: std.mem.Allocator,
    target: build_model.BuildTarget,
    output_path: []const u8,
    artifact_base_path: []const u8,
    emit: build_model.EmitOptions,
    input_paths: []const []const u8,
    graph_hash: []const u8,
) !void {
    const paths = try cachePaths(allocator, target, output_path, artifact_base_path, emit, graph_hash);
    defer freePaths(allocator, paths);

    var metadata = std.ArrayListUnmanaged(u8).empty;
    defer metadata.deinit(allocator);
    try metadata.appendSlice(allocator, magic[0 .. magic.len - 1]);
    try metadata.append(allocator, '\n');
    try metadata.appendSlice(allocator, paths.key);
    try metadata.append(allocator, '\n');
    for (input_paths) |path| {
        try appendInputRecord(allocator, &metadata, path);
    }
    for (target.c_sources.sources) |path| {
        try appendInputRecord(allocator, &metadata, path);
    }
    for (target.asm_sources.sources) |path| {
        try appendInputRecord(allocator, &metadata, path);
    }
    if (target.link.script) |path| {
        try appendInputRecord(allocator, &metadata, path);
    }

    const primary = try readArtifact(allocator, "primary", output_path);
    defer allocator.free(primary.contents);
    var artifacts: [2]bundle.Artifact = undefined;
    artifacts[0] = primary;
    var count: usize = 1;
    defer if (count == 2) allocator.free(artifacts[1].contents);
    if (target.output_kind == .staticlib) {
        const path = try std.fmt.allocPrint(allocator, "{s}.cyna-link.toml", .{output_path});
        defer allocator.free(path);
        artifacts[1] = try readArtifact(allocator, "link-metadata", path);
        count = 2;
    }
    try bundle.publish(allocator, paths.metadata, metadata.items, artifacts[0..count]);
}

fn appendInputRecord(allocator: std.mem.Allocator, metadata: *std.ArrayListUnmanaged(u8), path: []const u8) !void {
    var hash: [64]u8 = undefined;
    try hashFile(&hash, allocator, path);
    const record = try std.fmt.allocPrint(allocator, "input {s} {s}\n", .{ &hash, path });
    defer allocator.free(record);
    try metadata.appendSlice(allocator, record);
}

const CachePaths = struct {
    key: []u8,
    metadata: []u8,
};

fn cachePaths(
    allocator: std.mem.Allocator,
    target: build_model.BuildTarget,
    output_path: []const u8,
    artifact_base_path: []const u8,
    emit: build_model.EmitOptions,
    graph_hash: []const u8,
) !CachePaths {
    var hasher = std.crypto.hash.sha2.Sha256.init(.{});
    // Reject artifacts emitted before the nullable C-pointer ABI correction.
    hasher.update("cyna-build-input-v4\x00");
    hashString(&hasher, target.source_path);
    hashString(&hasher, graph_hash);
    hashString(&hasher, build_options.cyna_version);
    hashString(&hasher, target.compiler_identity);
    hashString(&hasher, target.target orelse "native");
    hashString(&hasher, target.cpu orelse "");
    hashString(&hasher, @tagName(target.output_kind));
    hashString(&hasher, @tagName(target.opt));
    hashString(&hasher, if (target.leak_check) "leak" else "no-leak");
    hashString(&hasher, output_path);
    hashString(&hasher, artifact_base_path);
    hashString(&hasher, if (emit.elf) "elf" else "no-elf");
    hashString(&hasher, if (emit.bin) "bin" else "no-bin");
    hashString(&hasher, if (emit.hex) "hex" else "no-hex");
    hashStringSlice(&hasher, target.link.libs);
    hashStringSlice(&hasher, target.link.search_paths);
    hashString(&hasher, target.link.script orelse "");
    hashString(&hasher, target.link.entry_symbol orelse "");
    hashNativeOptions(&hasher, target.c_sources);
    hashNativeOptions(&hasher, target.asm_sources);

    var digest: [std.crypto.hash.sha2.Sha256.digest_length]u8 = undefined;
    hasher.final(&digest);
    const key = try std.fmt.allocPrint(allocator, "{s}", .{std.fmt.bytesToHex(digest, .lower)});
    errdefer allocator.free(key);
    const dir = try std.fs.path.join(allocator, &.{ target.root_dir, ".cyna-cache", "builds" });
    defer allocator.free(dir);
    try compat.makePath(dir);
    return .{
        .key = key,
        .metadata = try std.fmt.allocPrint(allocator, "{s}/{s}.meta", .{ dir, key }),
    };
}

fn hashNativeOptions(hasher: *std.crypto.hash.sha2.Sha256, options: build_model.NativeSourceOptions) void {
    hashStringSlice(hasher, options.sources);
    hashStringSlice(hasher, options.include_paths);
    hashStringSlice(hasher, options.flags);
}

fn hashString(hasher: *std.crypto.hash.sha2.Sha256, value: []const u8) void {
    hasher.update(value);
    hasher.update("\x00");
}

fn hashStringSlice(hasher: *std.crypto.hash.sha2.Sha256, values: []const []const u8) void {
    for (values) |value| hashString(hasher, value);
    hasher.update("\x01");
}

fn hashFile(out: *[64]u8, allocator: std.mem.Allocator, path: []const u8) !void {
    const contents = try compat.readFileAlloc(allocator, path, 256 * 1024 * 1024);
    defer allocator.free(contents);
    var digest: [std.crypto.hash.sha2.Sha256.digest_length]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(contents, &digest, .{});
    out.* = std.fmt.bytesToHex(digest, .lower);
}

fn readArtifact(allocator: std.mem.Allocator, name: []const u8, path: []const u8) !bundle.Artifact {
    const file = try compat.openFile(path, .{});
    defer compat.closeFile(file);
    const stat = try file.stat(compat.io());
    const contents = try compat.readFileAlloc(allocator, path, 256 * 1024 * 1024);
    const mode: u32 = if (@import("builtin").os.tag == .windows) 0 else @intCast(stat.permissions.toMode() & 0o7777);
    return .{ .name = name, .contents = contents, .mode = mode };
}

fn freePaths(allocator: std.mem.Allocator, paths: CachePaths) void {
    allocator.free(paths.key);
    allocator.free(paths.metadata);
}

test "build artifact cache restores unchanged inputs and rejects source changes" {
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    const allocator = std.testing.allocator;
    const root = try compat.tmpDirRealpathAlloc(allocator, &tmp, ".");
    defer allocator.free(root);
    const source_path = try std.fs.path.join(allocator, &.{ root, "main.cy" });
    defer allocator.free(source_path);
    const output_path = try std.fs.path.join(allocator, &.{ root, "main.native" });
    defer allocator.free(output_path);
    try compat.writeTextFile(source_path, "fn main(): i32 { return 0; }\n");
    try compat.writeTextFile(output_path, "native-artifact\n");

    var target = build_model.BuildTarget{
        .is_project = false,
        .display_path = try allocator.dupe(u8, source_path),
        .root_dir = try allocator.dupe(u8, root),
        .source_path = try allocator.dupe(u8, source_path),
        .name = try allocator.dupe(u8, "main"),
    };
    defer target.deinit(allocator);

    try store(allocator, target, output_path, output_path, .{}, &.{source_path}, "graph");
    try compat.deleteFile(output_path);
    try std.testing.expect(!(try restore(allocator, target, output_path, output_path, .{}, "changed graph")));
    try std.testing.expect(try restore(allocator, target, output_path, output_path, .{}, "graph"));
    const restored = try compat.readFileAlloc(allocator, output_path, 1024);
    defer allocator.free(restored);
    try std.testing.expectEqualStrings("native-artifact\n", restored);

    try compat.writeTextFile(source_path, "fn main(): i32 { return 1; }\n");
    try compat.deleteFile(output_path);
    try std.testing.expect(!(try restore(allocator, target, output_path, output_path, .{}, "graph")));
}

test "build artifact cache validates the newly resolved dependency graph" {
    const loader = @import("../compiler/loader.zig");
    const modules = @import("modules.zig");
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    const allocator = std.testing.allocator;
    try compat.dirMakePath(tmp.dir, "dep_a");
    try compat.dirMakePath(tmp.dir, "dep_b");
    try compat.dirWriteFile(tmp.dir, .{ .sub_path = "main.cy", .data = "import cachedep.value; fn main(): i32 { return value.answer(); }" });
    try compat.dirWriteFile(tmp.dir, .{ .sub_path = "dep_a/value.cy", .data = "pub fn answer(): i32 { return 23; }" });
    try compat.dirWriteFile(tmp.dir, .{ .sub_path = "dep_b/value.cy", .data = "pub fn answer(): i32 { return 37; }" });
    try compat.dirWriteFile(tmp.dir, .{ .sub_path = "cyna.toml", .data = "entry = \"main.cy\"\n[dependencies]\ncachedep = { path = \"dep_a\" }\n" });
    const root = try compat.tmpDirRealpathAlloc(allocator, &tmp, ".");
    defer allocator.free(root);
    var target = try build_model.resolveBuildTarget(allocator, root);
    defer target.deinit(allocator);
    const output = try std.fs.path.join(allocator, &.{ root, "program" });
    defer allocator.free(output);
    try compat.writeTextFile(output, "old program");
    var previous = try loader.loadProgram(allocator, target.source_path);
    defer previous.deinit(allocator);
    var previous_plan = try modules.Plan.init(allocator, previous);
    defer previous_plan.deinit();
    var old_hasher = std.crypto.hash.sha2.Sha256.init(.{});
    previous_plan.updateHash(&old_hasher);
    var old_hash: [32]u8 = undefined;
    old_hasher.final(&old_hash);
    try store(allocator, target, output, output, .{}, previous.source_paths, &old_hash);
    // Declared dependency imports have a fixed root. A new same-spelling file
    // in the application's source root cannot shadow that dependency. Local
    // path dependencies likewise do not take their binding from the lockfile.
    try compat.dirMakePath(tmp.dir, "cachedep");
    try compat.dirWriteFile(tmp.dir, .{ .sub_path = "cachedep/value.cy", .data = "pub fn answer(): i32 { return 99; }" });
    try compat.dirWriteFile(tmp.dir, .{ .sub_path = "cyna.lock", .data = "[dependency.cachedep]\npackage = \"cachedep\"\nversion = \"9.9.9\"\n" });
    var unshadowed = try loader.loadProgram(allocator, target.source_path);
    defer unshadowed.deinit(allocator);
    var unshadowed_plan = try modules.Plan.init(allocator, unshadowed);
    defer unshadowed_plan.deinit();
    var unshadowed_hasher = std.crypto.hash.sha2.Sha256.init(.{});
    unshadowed_plan.updateHash(&unshadowed_hasher);
    var unshadowed_hash: [32]u8 = undefined;
    unshadowed_hasher.final(&unshadowed_hash);
    try std.testing.expectEqualSlices(u8, &old_hash, &unshadowed_hash);
    // None of the previously recorded source files changed. Only resolution
    // chooses a different dependency; checking the old graph cannot detect it.
    try compat.dirWriteFile(tmp.dir, .{ .sub_path = "cyna.toml", .data = "entry = \"main.cy\"\n[dependencies]\ncachedep = { path = \"dep_b\" }\n" });
    var current = try loader.loadProgram(allocator, target.source_path);
    defer current.deinit(allocator);
    var current_plan = try modules.Plan.init(allocator, current);
    defer current_plan.deinit();
    var new_hasher = std.crypto.hash.sha2.Sha256.init(.{});
    current_plan.updateHash(&new_hasher);
    var new_hash: [32]u8 = undefined;
    new_hasher.final(&new_hash);
    try std.testing.expect(!std.mem.eql(u8, &old_hash, &new_hash));
    try compat.deleteFile(output);
    try std.testing.expect(!(try restore(allocator, target, output, output, .{}, &new_hash)));
    try std.testing.expectError(error.FileNotFound, compat.access(output, .{}));
}

test "build artifact cache recreates executable output directories and permissions" {
    if (@import("builtin").os.tag == .windows) return error.SkipZigTest;
    const allocator = std.testing.allocator;
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    const root = try compat.tmpDirRealpathAlloc(allocator, &tmp, ".");
    defer allocator.free(root);
    const source = try std.fs.path.join(allocator, &.{ root, "main.cy" });
    defer allocator.free(source);
    try compat.writeTextFile(source, "fn main(): i32 { return 37; }");
    const output_dir = try std.fs.path.join(allocator, &.{ root, "output" });
    defer allocator.free(output_dir);
    const output = try std.fs.path.join(allocator, &.{ output_dir, "program" });
    defer allocator.free(output);
    try bundle.writeAtomic(output, "#!/bin/sh\nexit 37\n", 0o751);
    var target = build_model.BuildTarget{
        .is_project = false,
        .display_path = try allocator.dupe(u8, source),
        .root_dir = try allocator.dupe(u8, root),
        .source_path = try allocator.dupe(u8, source),
        .name = try allocator.dupe(u8, "main"),
    };
    defer target.deinit(allocator);
    try store(allocator, target, output, output, .{}, &.{source}, "graph");
    try compat.deleteTreeAbsolute(output_dir);
    try std.testing.expect(try restore(allocator, target, output, output, .{}, "graph"));
    const file = try compat.openFile(output, .{});
    defer compat.closeFile(file);
    try std.testing.expectEqual(@as(u32, 0o751), @as(u32, @intCast((try file.stat(compat.io())).permissions.toMode())) & 0o777);
    const result = try compat.runProcess(allocator, .{ .argv = &.{output} });
    defer allocator.free(result.stdout);
    defer allocator.free(result.stderr);
    try std.testing.expectEqual(@as(u8, 37), result.term.exited);
}

test "restored static library bundle is consumed by another native project" {
    if (@import("builtin").os.tag == .windows) return error.SkipZigTest;
    const allocator = std.testing.allocator;
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    const root = try compat.tmpDirRealpathAlloc(allocator, &tmp, ".");
    defer allocator.free(root);
    const source = try std.fs.path.join(allocator, &.{ root, "producer.c" });
    defer allocator.free(source);
    try compat.writeTextFile(source, "int answer(void) { return 42; }\n");
    const object = try std.fs.path.join(allocator, &.{ root, "producer.o" });
    defer allocator.free(object);
    const library_dir = try std.fs.path.join(allocator, &.{ root, "library" });
    defer allocator.free(library_dir);
    try compat.makePath(library_dir);
    const archive = try std.fs.path.join(allocator, &.{ library_dir, "libanswer.a" });
    defer allocator.free(archive);
    const sidecar = try std.fmt.allocPrint(allocator, "{s}.cyna-link.toml", .{archive});
    defer allocator.free(sidecar);
    const metadata = "version = 2\ndependencies = []\n";
    for ([_][]const []const u8{
        &.{ "cc", "-c", source, "-o", object },
        &.{ "ar", "rcs", archive, object },
    }) |argv| {
        const result = try compat.runProcess(allocator, .{ .argv = argv });
        defer allocator.free(result.stdout);
        defer allocator.free(result.stderr);
        try std.testing.expectEqual(@as(u8, 0), result.term.exited);
    }
    try compat.writeTextFile(sidecar, metadata);
    var target = build_model.BuildTarget{
        .is_project = false,
        .display_path = try allocator.dupe(u8, source),
        .root_dir = try allocator.dupe(u8, root),
        .source_path = try allocator.dupe(u8, source),
        .name = try allocator.dupe(u8, "answer"),
        .output_kind = .staticlib,
    };
    defer target.deinit(allocator);
    try store(allocator, target, archive, archive, .{}, &.{source}, "graph");
    try compat.deleteFile(sidecar);
    try std.testing.expectError(error.FileNotFound, store(allocator, target, archive, archive, .{}, &.{source}, "graph"));
    try compat.deleteTreeAbsolute(library_dir);
    try std.testing.expect(try restore(allocator, target, archive, archive, .{}, "graph"));
    const restored_metadata = try compat.readFileAlloc(allocator, sidecar, 1024);
    defer allocator.free(restored_metadata);
    try std.testing.expectEqualStrings(metadata, restored_metadata);
    const consumer = try std.fs.path.join(allocator, &.{ root, "consumer", "main.c" });
    defer allocator.free(consumer);
    try compat.writeTextFile(consumer, "extern int answer(void); int main(void) { return answer(); }\n");
    const executable = try std.fs.path.join(allocator, &.{ root, "consumer", "program" });
    defer allocator.free(executable);
    var consumer_target = build_model.BuildTarget{
        .is_project = false,
        .display_path = try allocator.dupe(u8, consumer),
        .root_dir = try allocator.dupe(u8, std.fs.path.dirname(consumer).?),
        .source_path = try allocator.dupe(u8, consumer),
        .name = try allocator.dupe(u8, "consumer"),
    };
    defer consumer_target.deinit(allocator);
    consumer_target.link.libs = try allocator.alloc([]const u8, 1);
    consumer_target.link.libs[0] = try allocator.dupe(u8, "answer");
    consumer_target.link.search_paths = try allocator.alloc([]const u8, 1);
    consumer_target.link.search_paths[0] = try allocator.dupe(u8, library_dir);
    const ir =
        \\declare i32 @answer()
        \\define i32 @main() {
        \\  %value = call i32 @answer()
        \\  ret i32 %value
        \\}
    ;
    const native = @import("native.zig");
    try std.testing.expect(try native.compileNativeArtifact(allocator, ir, .{}, consumer_target, false, true, executable, executable, .{}));
    const result = try compat.runProcess(allocator, .{ .argv = &.{executable} });
    defer allocator.free(result.stdout);
    defer allocator.free(result.stderr);
    try std.testing.expectEqual(@as(u8, 42), result.term.exited);
    // Replacing the same named archive must invalidate the native link entry,
    // even though the consumer IR and all library/search-path strings match.
    try compat.writeTextFile(source, "int answer(void) { return 37; }\n");
    for ([_][]const []const u8{
        &.{ "cc", "-c", source, "-o", object },
        &.{ "ar", "rcs", archive, object },
    }) |argv| {
        const rebuilt = try compat.runProcess(allocator, .{ .argv = argv });
        defer allocator.free(rebuilt.stdout);
        defer allocator.free(rebuilt.stderr);
        try std.testing.expectEqual(@as(u8, 0), rebuilt.term.exited);
    }
    try std.testing.expect(try native.compileNativeArtifact(allocator, ir, .{}, consumer_target, false, true, executable, executable, .{}));
    const changed = try compat.runProcess(allocator, .{ .argv = &.{executable} });
    defer allocator.free(changed.stdout);
    defer allocator.free(changed.stderr);
    try std.testing.expectEqual(@as(u8, 37), changed.term.exited);
    try compat.writeTextFile(sidecar, "version = 0\n");
    try std.testing.expectError(error.UnsupportedTarget, native.compileNativeArtifact(allocator, ir, .{}, consumer_target, false, true, executable, executable, .{}));
}
